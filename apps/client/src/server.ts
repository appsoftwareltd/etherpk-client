/**
 * The Client's production entry point, bundled to build/index.js by scripts/build-server.mjs in
 * place of adapter-node's own. It runs the adapter's server unchanged (its graceful shutdown,
 * socket activation and timeouts) and adds the ORIGIN setting, which adapter-node 6 no longer
 * reads (configured-origin.ts).
 */
import process from 'node:process'
import { configureOrigin } from '@appsoftwareltd/etherpk-shared/server/configured-origin'

// Before the adapter loads, which is why it is imported here and not at the top: this sets the
// adapter's header settings, and the adapter reads them once, when it loads.
const stampOrigin = configureOrigin(process.env)
// This module exists only after adapter-node has built, so @ts-expect-error would itself
// become an unused-directive error in any tree where the build has already run.
/* eslint-disable @typescript-eslint/ban-ts-comment */
// @ts-ignore -- generated by adapter-node at build time
const { server } = await import('./server/adapter-index.js')
/* eslint-enable @typescript-eslint/ban-ts-comment */
if (stampOrigin) server.prependListener('request', stampOrigin)
